    def test_stale_refresh_is_nonblocking_and_coalesced(self):
        cache_tools._service_cache.clear()
        now = [10000.0]
        calls = []
        entered = threading.Event()
        release = threading.Event()
        done = threading.Event()

        @cache_tools.stale_while_revalidate
        def service(key="A"):
            calls.append(key)
            if len(calls) > 1:
                entered.set()
                release.wait(3)
            return {"value": len(calls)}

        with patch.object(cache_tools.time, "time", side_effect=lambda: now[0]):
            self.assertEqual(service()["value"], 1)
            now[0] += 901
            first = service()
            self.assertEqual(first["cache_state"], "stale_while_revalidate")
            self.assertTrue(entered.wait(1))
            with ThreadPoolExecutor(max_workers=8) as pool:
                results = list(pool.map(lambda _: service(), range(16)))
            self.assertTrue(all(result["value"] == 1 for result in results))
            self.assertEqual(len(calls), 2)
            release.set()
            cache_tools._executor.submit(done.set)
            # Wait for the per-key flag to clear, not for a timing assumption.
            import time

            deadline = time.monotonic() + 3
            while cache_tools._refreshing and time.monotonic() < deadline:
                threading.Event().wait(0.01)
            self.assertFalse(cache_tools._refreshing)
            self.assertEqual(service()["value"], 2)
